/**
 * An inline SVG icon. With `label` it's announced; otherwise it's decorative.
 * Sizes: 18 for header and row actions, 15 for tool rows, 14 for inline meta.
 */
export function icon(name, { cls = "", label = "", size = 18, stroke = 1.75 } = {}) {
  const a11y = label ? `role="img" aria-label="${label}"` : `aria-hidden="true"`;
  return `<svg class="icon lucide ${cls}" ${a11y} width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">${PATHS[name]}</svg>`;
}

/** Fill in `<svg data-icon="name" data-size="15" data-stroke="2">` placeholders in static HTML. */
export function fillIcons(root = document) {
  for (const el of root.querySelectorAll("[data-icon]")) {
    const { icon: name, size, stroke } = el.dataset;
    el.outerHTML = icon(name, { cls: el.getAttribute("class") ?? "", size: Number(size) || 18, stroke: Number(stroke) || 1.75 });
  }
}

let markSeq = 0;

/**
 * The Eyepatch mark: a rounded square with an eye patch and strap cut out.
 * Below 24 px it uses a heavier cut so the strap survives. Uses currentColor.
 */
export function mark({ size = 48, cls = "", label = "" } = {}) {
  const id = `eyepatch-cut-${++markSeq}`;
  const heavy = size < 24;
  const strap = heavy ? `y="37" height="10"` : `y="39" height="6"`;
  const patch = heavy ? `x="21" y="26.5" width="34" height="31" rx="11"` : `x="23" y="28.5" width="30" height="27" rx="10"`;
  const a11y = label ? `role="img" aria-label="${label}"` : `aria-hidden="true"`;
  return `<svg class="mark ${cls}" ${a11y} width="${size}" height="${size}" viewBox="0 0 100 100">` +
    `<mask id="${id}"><rect width="100" height="100" fill="white"/>` +
    `<rect x="-82" ${strap} width="240" fill="black" transform="rotate(-24 38 42)"/>` +
    `<rect ${patch} fill="black" transform="rotate(-24 38 42)"/></mask>` +
    `<rect x="4" y="4" width="92" height="92" rx="24" fill="currentColor" mask="url(#${id})"/></svg>`;
}
